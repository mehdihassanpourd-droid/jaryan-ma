import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { validateProductInput } from "../src/domain/product/schema";
import { buildCatalogSeo } from "../src/seo/catalog-seo";
import { loadSnapshotCatalog, type SnapshotReader } from "../src/seo/catalog-source";
import { breadcrumbJsonLd, productJsonLd, serializeJsonLd } from "../src/seo/jsonld";
import { buildRobots, buildSitemap } from "../src/seo/sitemap";
import { PrismaCatalogRepository } from "./catalog/prisma-repository";
import { CatalogService } from "./catalog/service";
import { SnapshotPublisher } from "./catalog/snapshot-publisher";
import { createTestDatabase, type TestDatabase } from "./db/test-database";
import { ensureDefaultVendor } from "./db/vendor";
import { MemoryStorage } from "./storage/memory";

/**
 * End to end with the REAL backend: products are created through the catalogue service on PostgreSQL, published as
 * snapshots by the real publisher, and the SEO layer works from those published files only.
 */
const MEDIA = "https://media.example.ir";
const ORIGIN = "https://jaryan.example.ir";
const ACTOR = "owner@example.test";

let testDb: TestDatabase;
let repo: PrismaCatalogRepository;
let service: CatalogService;
let storage: MemoryStorage;
let publisher: SnapshotPublisher;

beforeAll(async () => void (testDb = await createTestDatabase()), 60_000);
afterAll(async () => testDb.close());

beforeEach(async () => {
  await testDb.reset();
  repo = new PrismaCatalogRepository(testDb.db, await ensureDefaultVendor(testDb.db));
  service = new CatalogService(repo);
  storage = new MemoryStorage();
  publisher = new SnapshotPublisher(repo, storage, MEDIA);
});

const reader = (): SnapshotReader => ({ readText: async (path) => storage.text(path) ?? null });

async function publish(raw: Record<string, unknown>, status: "published" | "draft" | "archived" = "published") {
  const parsed = validateProductInput({ fulfillment: "unique", ...raw });
  if (!parsed.ok) throw new Error(JSON.stringify(parsed.issues));
  let product = await service.create({ ...parsed.value, status: "draft" }, ACTOR);
  if (status !== "draft") product = await service.setStatus(product.id, status, product.version, ACTOR);
  await publisher.sync([{ id: product.id }]);
  return product;
}

async function seo(settings = { origin: ORIGIN as string | null, indexing: true }) {
  const catalog = await loadSnapshotCatalog(reader());
  return { catalog, seo: buildCatalogSeo(catalog, settings, "جریان ما") };
}

describe("SEO output from the real PostgreSQL backend", () => {
  it("builds unique Persian URLs, titles, descriptions, canonicals, JSON-LD and a sitemap for published products only", async () => {
    const walls = (await repo.createCategory({ slug: "دیوارکوب", name: "دیوارکوب بافته" })).id;
    const macrame = (await repo.createCategory({ slug: "ماکرومه", name: "ماکرومه" })).id;
    await repo.createCategory({ slug: "خالی", name: "دسته خالی" });

    const a = await publish({ name: "دیوارکوب پاییزی", description: "", categoryId: walls, priceToman: 4_500_000, images: [{ key: "images/pa/1.webp", alt: "دیوارکوب پاییزی روی دیوار" }, { key: "images/pa/2.webp", alt: "" }] });
    const b = await publish({ name: "ماکرومه قوسی", categoryId: macrame, priceToman: 1_200_000, images: [{ key: "images/pb/1.webp", alt: "" }] });
    const dup1 = await publish({ name: "ماکرومه قوسی", categoryId: macrame, priceToman: 900_000, images: [{ key: "images/pc/1.webp", alt: "نمای دیگر" }] });
    await publish({ name: "پیش‌نویس", categoryId: walls }, "draft");
    await publish({ name: "آرشیوشده", categoryId: walls }, "archived");
    const made = await publish({ name: "رانر سفارشی", fulfillment: "made_to_order", leadTimeDays: 21, categoryId: walls, priceToman: 2_000_000, images: [{ key: "images/pd/1.webp", alt: "رانر" }] });
    const variants = await publish({
      name: "کوسن بافته",
      fulfillment: "stocked",
      categoryId: walls,
      variants: [{ sku: "K-S", options: { size: "S" }, inventory: 2, priceToman: 500_000 }, { sku: "K-L", options: { size: "L" }, inventory: 0, priceToman: 800_000 }],
      images: [{ key: "images/pe/1.webp", alt: "کوسن" }],
    });
    const sold = await publish({ name: "اثر فروخته‌شده", categoryId: walls, inventory: 0, priceToman: 1_000_000, images: [{ key: "images/pf/1.webp", alt: "اثر" }] });

    const { catalog, seo: s } = await seo();
    const slugs = catalog.products.map((p) => p.slug);

    // Published only; the empty category produces nothing.
    expect(slugs).toEqual(expect.arrayContaining([a.slug, b.slug, dup1.slug, made.slug, variants.slug, sold.slug]));
    expect(slugs).toHaveLength(6);
    expect(catalog.categories.map((c) => c.slug).sort()).toEqual(["دیوارکوب", "ماکرومه"].sort());

    // Persian slugs generated by the backend are used as-is and percent-encoded in URLs.
    expect(a.slug).toBe("دیوارکوب-پاییزی");
    expect(s.products.get(a.slug)!.canonical).toBe(`${ORIGIN}/products/${encodeURIComponent(a.slug)}`);

    // Unique titles and descriptions, even for two products with the same name.
    const titles = [...s.products.values()].map((p) => p.title);
    const descriptions = [...s.products.values()].map((p) => p.description);
    expect(new Set(titles).size).toBe(titles.length);
    expect(new Set(descriptions).size).toBe(descriptions.length);
    expect(titles.filter((t) => t.startsWith("ماکرومه قوسی"))).toHaveLength(2);
    for (const d of descriptions) expect(d.length).toBeLessThanOrEqual(160);

    // Alt text: the editor's text when present, derived from the name otherwise.
    const imagesOfA = s.products.get(a.slug)!.images;
    expect(imagesOfA.map((i) => i.alt)).toEqual(["دیوارکوب پاییزی روی دیوار", "دیوارکوب پاییزی (تصویر ۲ از ۲)"]);
    expect(imagesOfA[0]!.url).toBe(`${MEDIA}/images/pa/1.webp`);

    // Product JSON-LD: only verified facts, Rial prices as exact strings.
    const ldA = productJsonLd(catalog.products.find((p) => p.slug === a.slug)!, s)!;
    expect(ldA).toMatchObject({ "@type": "Product", name: "دیوارکوب پاییزی", offers: { price: "45000000", priceCurrency: "IRR", availability: "https://schema.org/InStock" } });
    // (The backend refuses to publish a product without a price, so every published product has an offer; the
    // "no price, no offer" rule is covered by the unit tests as a second line of defence.)
    expect(productJsonLd(catalog.products.find((p) => p.slug === b.slug)!, s)!.offers).toMatchObject({ price: "12000000" });
    expect(productJsonLd(catalog.products.find((p) => p.slug === made.slug)!, s)!.offers).toMatchObject({ availability: "https://schema.org/MadeToOrder" });
    expect(productJsonLd(catalog.products.find((p) => p.slug === sold.slug)!, s)!.offers).toMatchObject({ availability: "https://schema.org/OutOfStock" });
    expect(productJsonLd(catalog.products.find((p) => p.slug === variants.slug)!, s)!.offers).toMatchObject({ "@type": "AggregateOffer", lowPrice: "5000000", highPrice: "8000000", offerCount: 2 });
    expect(s.products.get(made.slug)!.description).toContain("زمان ساخت: ۲۱ روز");

    // Breadcrumbs link home > category > product.
    const crumbs = breadcrumbJsonLd(catalog.products.find((p) => p.slug === a.slug)!, s)!.itemListElement as Array<{ item: string }>;
    expect(crumbs.map((c) => c.item)).toEqual([`${ORIGIN}/`, `${ORIGIN}/category/${encodeURIComponent("دیوارکوب")}`, s.products.get(a.slug)!.canonical]);

    // Sitemap: home + both categories + the six real products; nothing else.
    const urls = buildSitemap(s).map((e) => e.url);
    expect(urls).toHaveLength(1 + 2 + 6);
    expect(urls).not.toEqual(expect.arrayContaining([expect.stringContaining(encodeURIComponent("پیش‌نویس"))]));
    expect(urls.every((u) => u.startsWith(`${ORIGIN}/`))).toBe(true);
    expect(new Set(urls).size).toBe(urls.length);
  });

  it("updates automatically when the catalogue changes: renames, unpublishing and new products", async () => {
    const cat = (await repo.createCategory({ slug: "دیوارکوب", name: "دیوارکوب" })).id;
    const p = await publish({ name: "اثر اول", categoryId: cat, priceToman: 1_000_000, images: [{ key: "images/p1/1.webp", alt: "اول" }] });
    expect((await seo()).catalog.products.map((x) => x.slug)).toEqual([p.slug]);

    // rename -> new slug, old URL disappears
    const edit = validateProductInput({ fulfillment: "unique", name: "اثر تازه", slug: "اثر-تازه", categoryId: cat, priceToman: 1_000_000, status: "published", images: [{ key: "images/p1/1.webp", alt: "اول" }] });
    if (!edit.ok) throw new Error(JSON.stringify(edit.issues));
    const renamed = await service.update(p.id, edit.value, p.version, ACTOR);
    await publisher.sync([{ id: p.id, previousSlug: p.slug, previousCategoryId: cat }]);
    expect((await seo()).catalog.products.map((x) => x.slug)).toEqual([renamed.slug]);

    // unpublish -> gone from products and sitemap
    await service.setStatus(p.id, "draft", renamed.version, ACTOR);
    await publisher.sync([{ id: p.id, previousSlug: renamed.slug, previousCategoryId: cat }]);
    const empty = await seo();
    expect(empty.catalog.products).toEqual([]);
    expect(buildSitemap(empty.seo).map((e) => e.url)).toEqual([`${ORIGIN}/`]);
  });

  it("handles the largest supported price and hostile text without breaking the structured data", async () => {
    const cat = (await repo.createCategory({ slug: "دیوارکوب", name: "دیوارکوب" })).id;
    const evil = await publish({ name: "اثر </script><b>x</b>", description: "</script><script>alert(1)</script> & \"quotes\"", categoryId: cat, priceToman: 1_000_000_000_000_000, images: [{ key: "images/pz/1.webp", alt: "<img src=x onerror=alert(1)>" }] });
    const { catalog, seo: s } = await seo();
    const product = catalog.products.find((p) => p.slug === evil.slug)!;
    const ld = productJsonLd(product, s)!;
    expect((ld.offers as { price: string }).price).toBe("10000000000000000");
    const html = serializeJsonLd(ld);
    expect(html).not.toMatch(/[<>]/);
    expect(JSON.parse(html).name).toBe(product.name);
    expect(s.products.get(evil.slug)!.images[0]!.alt).not.toContain("<");
    expect(s.products.get(evil.slug)!.description).not.toContain("<");
  });

  it("stays closed before launch: nothing indexable, robots disallow, JSON-LD still never invents data", async () => {
    const cat = (await repo.createCategory({ slug: "دیوارکوب", name: "دیوارکوب" })).id;
    await publish({ name: "اثر", categoryId: cat, priceToman: 1_000_000, images: [{ key: "images/p1/1.webp", alt: "اثر" }] });
    const { seo: s } = await seo({ origin: ORIGIN, indexing: false });
    expect([...s.products.values()].every((p) => !p.indexable)).toBe(true);
    expect(buildRobots(ORIGIN, false)).toEqual({ rules: { userAgent: "*", disallow: "/" } });
  });
});
